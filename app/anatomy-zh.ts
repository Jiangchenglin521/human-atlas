function latinMuscle(words: string[]) {
  const action = ACTION[words[0]];
  if (!action || words.length < 2) return null;
  const parts: string[] = [];
  const mods: string[] = [];
  for (const word of words.slice(1)) {
    if (MUSCLE_PART[word]) parts.push(MUSCLE_PART[word]);
    else if (MUSCLE_MOD[word]) mods.push(MUSCLE_MOD[word]);
    else return null;
  }
  let part = parts.join('');
  if (parts.length === 2 && parts[0] === '指' && parts[1] === '小指') part = '小指';
  if (parts.length === 2 && parts[0] === '指' && parts[1] === '示指') part = '示指';
  return `${part}${mods.join('')}${action}肌`;
}

function applyPhrases(input: string) {
  let text = input;
  const slots: string[] = [];
  for (const [en, zh] of PHRASES) {
    const escaped = en.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    text = text.replace(new RegExp(`\\b${escaped}\\b`, 'gi'), () => {
      const index = slots.length;
      slots.push(zh);
      return ` §${index}§ `;
    });
  }
  return {text, slots};
}

function translateSegment(segment: string) {
  const phrased = applyPhrases(segment);
  const text = phrased.text.replace(/-/g, ' ');
  const tokens = text.match(/§\d+§|[a-z0-9]+/g) ?? [];
  const resolved = tokens.map(token => token.startsWith('§') ? phrased.slots[Number(token.slice(1, -1))] : token);
  if (resolved.length > 1 && resolved.every(token => /^[a-z0-9]+$/.test(token))) {
    const muscle = latinMuscle(resolved);
    if (muscle) return muscle;
  }
  let side = '';
  let proper = false;
  const pieces: string[] = [];
  for (const token of resolved) {
    if (!/^[a-z0-9]+$/.test(token)) {
      pieces.push(token);
      continue;
    }
    if (token === 'left') { side += '左'; continue; }
    if (token === 'right') { side += '右'; continue; }
    if (token === 'proper') { proper = true; continue; }
    const word = WORDS[token];
    if (word === undefined) pieces.push(token);
    else if (word) pieces.push(word);
  }
  let body = pieces.join('');
  if (proper) {
    const head = HEADS.find(item => body.includes(item));
    body = head ? body.replace(head, `固有${head}`) : `固有${body}`;
  }
  return side + body;
}

function translateTooth(name: string) {
  const match = name.match(/^(left|right) (upper|lower) (?:(first|second|third) )?(?:(central|lateral) )?(primary|secondary) (incisor|canine|premolar|molar) tooth$/);
  if (!match) return null;
  const [, side, jaw, ordinal, position, dentition, kind] = match;
  const ordinalZh = ordinal === 'first' ? '第一' : ordinal === 'second' ? '第二' : ordinal === 'third' ? '第三' : '';
  const positionZh = position === 'central' ? '中' : position === 'lateral' ? '侧' : '';
  const dentitionZh = dentition === 'secondary' ? '恒' : '乳';
  const kindZh = {incisor: '切牙', canine: '尖牙', premolar: '前磨牙', molar: '磨牙'}[kind];
  return `${side === 'left' ? '左' : '右'}${jaw === 'upper' ? '上' : '下'}${ordinalZh}${positionZh}${dentitionZh}${kindZh}`;
}

function finish(result: string, source: string) {
  let text = result.replace(/段([IVX]+)/g, '$1段').replace(/\s+/g, '');
  if (/\b(toe|toes|foot|plantar|hallucis|pedis|metatarsal|calcaneal)\b/i.test(source)) text = text.replace(/指/g, '趾');
  return text;
}

function translateRaw(original: string): string {
  const compact = original.trim().replace(/\s+/g, ' ');
  if (!/[a-z]/i.test(compact)) return compact;
  let name = compact.toLowerCase();
  const tooth = translateTooth(name);
  if (tooth) return tooth;
  let suffix = '';
  name = name.replace(/\s*\(([^)]*)\)\s*/g, (_, inner: string) => {
    suffix += `（${translateRaw(inner)}）`;
    return ' ';
  }).replace(/\s+/g, ' ').trim();
  if (name.startsWith('set of ')) return finish(`${translateRaw(name.slice(7))}组${suffix}`, original);
  const communicating = name.match(/^communicating branch of (.+) with (.+)$/);
  if (communicating) return finish(`${translateRaw(communicating[1])}与${translateRaw(communicating[2])}交通支${suffix}`, original);
  const toward = name.match(/^(?:branch|branches) of (.+) to (.+)$/);
  if (toward) return finish(`${translateRaw(toward[1])}至${translateRaw(toward[2])}支${suffix}`, original);
  const segments = name.split(' of ').map(segment => translateSegment(segment.trim()));
  return finish(`${segments.reverse().join('')}${suffix}`, original);
}

/** Standard Chinese anatomical name for a BodyParts3D English label. */
export function toZh(name: string) {
  const key = name.trim().toLowerCase();
  const cached = cache.get(key);
  if (cached) return cached;
  const translated = translateRaw(name);
  cache.set(key, translated);
  return translated;
}

